package database

import (
	"fmt"
	"slices"
	"strconv"
	"strings"
)

// ddl creates what is missing, idempotently: the schemas, the tables, their
// columns and their indexes, in foreign key order. It never drops or changes
// a column.
func ddl(tables []*table) []string {
	var stmts []string
	for _, t := range tables {
		if stmt := t.createSchema(); stmt != "" && !slices.Contains(stmts, stmt) {
			stmts = append(stmts, stmt)
		}
	}
	for _, t := range tables {
		stmts = append(stmts, t.create())
		for _, c := range t.columns {
			stmts = append(stmts, "alter table "+t.quoted()+" add column if not exists "+c.definition())
		}
		for _, i := range t.indexes() {
			stmts = append(stmts, i.sql)
		}
	}
	return stmts
}

// createSchema creates the schema of "schema.table"; "" for a bare table.
func (t *table) createSchema() string {
	if i := strings.LastIndex(t.name, "."); i > 0 {
		return "create schema if not exists " + quoteTable(t.name[:i])
	}
	return ""
}

func (t *table) create() string {
	defs := make([]string, len(t.columns))
	for i, c := range t.columns {
		defs[i] = c.definition()
	}
	var keys []string
	for _, c := range t.pk() {
		keys = append(keys, quote(c.name))
	}
	defs = append(defs, "primary key ("+strings.Join(keys, ", ")+")")
	return "create table if not exists " + t.quoted() + " (\n\t" + strings.Join(defs, ",\n\t") + "\n)"
}

// drops removes the tables, the referencing ones first.
func drops(tables []*table) []string {
	stmts := make([]string, 0, len(tables))
	for _, t := range slices.Backward(tables) {
		stmts = append(stmts, "drop table if exists "+t.quoted()+" cascade")
	}
	return stmts
}

func (c column) definition() string {
	def := quote(c.name) + " " + c.sqlType
	if c.size > 0 {
		def += "(" + strconv.Itoa(c.size) + ")"
	}
	if c.generated == "auto_increment" {
		def += " generated by default as identity"
	}
	if !c.nullable {
		def += " not null"
	}
	switch {
	case c.generated == "uuid":
		def += " default gen_random_uuid()"
	case c.def != "":
		def += " default " + c.def
	case c.version:
		def += " default 0"
	}
	if c.fk != "" {
		def += " references " + quoteTable(c.fk)
		if c.onDelete != "" {
			def += " on delete " + c.onDelete
		}
	}
	return def
}

type index struct {
	name string // unquoted, in the table's schema
	sql  string
}

// indexes creates one index per group, in column order: the unique ones,
// "<table>_<group>_key", then the others, "<table>_<group>_idx".
func (t *table) indexes() []index {
	var all []index
	for _, kind := range []string{"unique", ""} {
		var order []string
		cols := map[string][]string{}
		for _, c := range t.columns {
			g := c.index
			if kind != "" {
				g = c.unique
			}
			if g != "" {
				if _, ok := cols[g]; !ok {
					order = append(order, g)
				}
				cols[g] = append(cols[g], quote(c.name))
			}
		}
		suffix, create := "_idx", "create index"
		if kind != "" {
			suffix, create = "_key", "create unique index"
		}
		base := t.name[strings.LastIndex(t.name, ".")+1:]
		for _, g := range order {
			name := base + "_" + g + suffix
			all = append(all, index{name, fmt.Sprintf("%s if not exists %s on %s (%s)",
				create, quote(name), t.quoted(), strings.Join(cols[g], ", "))})
		}
	}
	return all
}

// ordered sorts tables so each comes after the tables its foreign keys
// reference, and checks that they reference a model's single column key.
//
// ponytail: foreign keys are inline, so a cycle between tables is an error;
// split them into "alter table ... add constraint" if someone needs one.
func ordered(tables []*table) ([]*table, error) {
	byName := map[string]*table{}
	for _, t := range tables {
		byName[t.name] = t
	}
	const visiting, done = 1, 2
	state := map[*table]int{}
	var sorted []*table
	var visit func(t *table, path []string) error
	visit = func(t *table, path []string) error {
		switch state[t] {
		case done:
			return nil
		case visiting:
			return fmt.Errorf("database: foreign key cycle: %s", strings.Join(append(path, t.name), " -> "))
		}
		state[t] = visiting
		for _, c := range t.columns {
			ref, ok := byName[c.fk]
			switch {
			case c.fk == "" || ref == t:
				continue
			case !ok:
				return fmt.Errorf("database: %v.%s: fk:%q is not the table of a repository's model", t.typ, c.name, c.fk)
			case len(ref.pk()) != 1:
				return fmt.Errorf("database: %v.%s: fk:%q has a composite key", t.typ, c.name, c.fk)
			}
			if err := visit(ref, append(path, t.name)); err != nil {
				return err
			}
		}
		state[t] = done
		sorted = append(sorted, t)
		return nil
	}
	for _, t := range tables {
		if err := visit(t, nil); err != nil {
			return nil, err
		}
	}
	return sorted, nil
}
